def _split_pkgs(pkgs:str):
    "Split a comma-separated package list, ignoring the commas inside extras like `rishi[litert,llama]`"
    return [p for p in re.sub(r'\[[^\]]*\]', '', pkgs).split(',') if p.strip()]

